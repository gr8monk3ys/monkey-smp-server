"""The Build Battle block wheel: a draw anyone can check.

    python tools/block_wheel.py SEED            three spins for SEED (say "S1 launch") and the tellraw to announce them
    python tools/block_wheel.py SEED --spins 5
    python tools/block_wheel.py --pool REPORTS  rebuild tools/wheel_pool.txt from the game's data reports

Publish the seed before the spin (in #monkey-smp). Spin i draws index sha256("SEED:i") mod the pool size
from the pool file, skipping a block already drawn, so anyone with the repo gets the same blocks and
nobody can pick the seed after seeing the result.

The pool is every block that is also an item in this Minecraft version, minus what a survival player
can't get before the End opens (docs/SEASONS.md, Build Battle). Make REPORTS with the server jar:
    java -cp "<every jar under libraries>;versions/26.3/server-26.3.jar" net.minecraft.data.Main --reports
"""
import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

from repo import REPO

POOL = REPO.root / "tools" / "wheel_pool.txt"
MINECRAFT = "26.3"

# Blocks that have an item but can't be obtained in survival, or only in or after the End.
UNOBTAINABLE = re.compile(
    r"(^|_)(air|barrier|bedrock|command_block|structure_block|structure_void|jigsaw|light|test_block|"
    r"test_instance_block|spawner|vault|reinforced_deepslate|budding_amethyst|end_portal_frame|"
    r"petrified_oak_slab|player_head|farmland|dirt_path|frogspawn|suspicious_sand|suspicious_gravel)$|"
    r"^infested_")
END_ONLY = re.compile(r"(^|_)(end_stone|end_rod|purpur|chorus|dragon|shulker_box)")


def eligible(name: str) -> bool:
    return not UNOBTAINABLE.search(name) and not END_ONLY.search(name)


def build_pool(reports: Path) -> list[str]:
    registries = json.loads((reports / "registries.json").read_text(encoding="utf-8"))
    blocks = json.loads((reports / "blocks.json").read_text(encoding="utf-8"))
    items = {k.removeprefix("minecraft:") for k in registries["minecraft:item"]["entries"]}
    return sorted(b for b in (k.removeprefix("minecraft:") for k in blocks) if b in items and eligible(b))


def load_pool(path: Path = POOL) -> list[str]:
    return [line for line in path.read_text(encoding="utf-8").splitlines() if line and not line.startswith("#")]


def save_pool(pool: list[str], path: Path = POOL) -> None:
    header = [f"# Build Battle wheel pool for Minecraft {MINECRAFT}: one block id a line (generated by",
              "# python tools/block_wheel.py --pool; see that file for what is left out and why)."]
    path.write_bytes(("\n".join(header + pool) + "\n").encode())


def draw(seed: str, pool: list[str], spins: int = 3) -> list[str]:
    if spins > len(pool):
        raise ValueError("more spins than blocks")
    out: list[str] = []
    i = 0
    while len(out) < spins:
        pick = pool[int(hashlib.sha256(f"{seed}:{i}".encode()).hexdigest(), 16) % len(pool)]
        if pick not in out:
            out.append(pick)
        i += 1
    return out


def tellraw(seed: str, blocks: list[str]) -> str:
    parts: list[object] = [{"text": "Build Battle wheel: ", "color": "gold"}]
    for n, b in enumerate(blocks):
        if n:
            parts.append({"text": ", ", "color": "gray"})
        parts.append({"translate": f"block.minecraft.{b}", "color": "green"})
    parts.append({"text": f" (seed {seed})", "color": "dark_gray"})
    return "tellraw @a " + json.dumps(parts, separators=(",", ":"))


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="Draws Build Battle wheel blocks from a published seed.")
    ap.add_argument("seed", nargs="?", help="the published seed")
    ap.add_argument("--spins", type=int, default=3)
    ap.add_argument("--pool", type=Path, metavar="REPORTS", help="rebuild the pool from a data reports folder")
    args = ap.parse_args(argv)
    if args.pool:
        pool = build_pool(args.pool)
        save_pool(pool)
        print(f"wrote {len(pool)} blocks to {POOL.relative_to(REPO.root)}")
        return 0
    if not args.seed:
        ap.error("give a seed, or --pool")
    pool = load_pool()
    blocks = draw(args.seed, pool, args.spins)
    print(f"seed {args.seed!r}, pool of {len(pool)} blocks:")
    for n, b in enumerate(blocks, 1):
        print(f"  {n}. {b.replace('_', ' ')}  (minecraft:{b})")
    print("\nAnnounce in game:\n" + tellraw(args.seed, blocks))
    return 0


if __name__ == "__main__":
    sys.exit(main())
