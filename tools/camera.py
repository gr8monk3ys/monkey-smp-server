"""The creator camera: approved creators film the server in spectator with `/trigger camera`.

    python tools/datapacks.py      regenerate the monkey-camera data pack (with the others)

A creator staff have approved (`camera/approve`) toggles it with `/trigger camera`: spectator mode and a menu of
camera warps (spawn, the standings board, the four outposts, the event on now). Toggling it off puts them back
exactly where they were, in the game mode they were in, so the camera is never a way to travel or to escape.

This is a factions server, and a spectator sees through walls, so the rules keep it from being a scouting tool
(docs/ADMIN.md, "Creator camera"; RULES below):
  - Staff only grant it, one creator at a time (`camera/approve {name:"..."}`), and can take it back.
  - Only during a camera window staff open for an announced event (`camera/open {minutes:120}`). Opening and
    closing it is announced in chat, and so is each creator going into and out of camera.
  - Not for a faction member: a creator with a faction number (`st.faction`) can't go in, and one who joins a
    faction is taken out. The number is as fresh as the hourly board run (diplomacy.py).
  - A leash, checked every tick: the camera stays in the Overworld within LEASH blocks (either way) of the last
    warp, and going in always starts at the spawn warp, so it only ever looks at public places (spawn, the
    board, outposts, the arena, a drop: drops and outposts keep 96 blocks from claims). Spectator teleports to
    players and anything farther snap back within a tick.
  - Rule 10 (docs/RULES.md, no stream sniping): the creator streams with a delay of 5 minutes or more, and
    shares no coordinates, bases or positions (RULES, shown on approval and on every entry).
  - Not from the event arena, and not within HURT_SECONDS of being hurt.
Every second the pack checks the rest again and takes out whoever no longer passes, so closing the window,
revoking, `camera/off` or a new faction number end it within a second, offline creators at their next login.

Off by default: `function monkey:camera/on`. Stdlib only.
"""
from pathlib import Path

from datapacks import NS, function_tag, lines, mcmeta, refuse, say, text
from diplomacy import FACTION
from drops import OBJ as DROPS_OBJ
from drops import STORE as DROPS_STORE
from events import ARENA_TAG
from events import STORE as EVENTS_STORE
from outposts import DIRECTIONS
from outposts import STORE as OUTPOSTS_STORE
from repo import Repo
from standings import BOARD_TAG

DATAPACK = "monkey-camera"
FN = f"data/{NS}/function/camera"
STORE = f"{NS}:camera"
TRIGGER = "camera"
OBJ = "cm"          # #on (the switch), #open (seconds left in the camera window), scratch values
OK = "cm.ok"        # 1: staff approved this creator
IN = "cm.in"        # 1: in camera now
HURT = "cm.hurt"    # damage taken (a stat), read once a second
WAIT = "cm.wait"    # seconds until a creator who was hurt may go in
SAVED = ("cm.x", "cm.y", "cm.z")    # where they went in, x100
DIM = "cm.dim"      # 0 Overworld, 1 Nether, 2 End
MODE = "cm.mode"    # 0 survival, 1 creative, 2 adventure, 3 spectator
ANCHOR = ("cm.ax", "cm.az")         # the leash's middle
LEASH = 64          # under drops.CLAIM_GAP (96 blocks): the warps' places keep that far from claims
HURT_SECONDS = 15
WINDOW_MINUTES = 120    # the default camera window
DIMENSIONS = ("overworld", "the_nether", "the_end")
MODES = ("survival", "creative", "adventure", "spectator")

# The warps: /trigger camera set N. 1 toggles; 2 shows the menu again. Append new ones after the last.
WARPS = [("spawn", "Spawn", 3), ("board", "Board", 4)] + [
    (key, name, 5 + i) for i, (key, name, _) in enumerate(DIRECTIONS)] + [("event", "Event", 9)]

RULES = ("Camera rules: stream it with a delay of 5 minutes or more (rule 10: nobody snipes from your stream); "
         "no coordinates, bases or player positions shared with anyone, on stream or off; the camera stays near "
         "its warp; staff can take it back.")


def gray(s: str) -> dict:
    return {"text": s, "color": "gray"}


def button(label: str, value: int, hover: str, color: str = "aqua") -> dict:
    return {"text": f"[{label}] ", "color": color, "hover_event": {"action": "show_text", "value": hover},
            "click_event": {"action": "run_command", "command": f"/trigger {TRIGGER} set {value}"}}


def datapack_files() -> dict[str, str]:
    f: dict[str, str] = {}
    f["pack.mcmeta"] = mcmeta("Monkey SMP creator camera: spectator for approved creators (generated by "
                              "tools/camera.py)")
    f["data/minecraft/tags/function/load.json"] = function_tag(f"{NS}:camera/load")
    f["data/minecraft/tags/function/tick.json"] = function_tag(f"{NS}:camera/tick")
    f[f"{FN}/tick.mcfunction"] = lines(
        "# Every tick: the leash, so a spectator teleport never shows more than a tick of anywhere else.",
        f"execute as @a[scores={{{IN}=1}}] run function {NS}:camera/leash",
    )
    f[f"{FN}/load.mcfunction"] = lines(
        "# Generated by tools/camera.py. Off until staff turn it on (docs/ADMIN.md, \"Creator camera\").",
        f"scoreboard objectives add {TRIGGER} trigger",
        f"scoreboard objectives add {OBJ} dummy",
        *(f"scoreboard objectives add {o} dummy" for o in (OK, IN, WAIT, DIM, MODE, *SAVED, *ANCHOR)),
        f"scoreboard objectives add {HURT} minecraft.custom:minecraft.damage_taken",
        f"scoreboard players add #on {OBJ} 0",
        f"scoreboard players add #open {OBJ} 0",
        f"scoreboard players set #60 {OBJ} 60",
        f"schedule function {NS}:camera/second 20t replace",
    )
    f[f"{FN}/second.mcfunction"] = lines(
        f"schedule function {NS}:camera/second 20t replace",
        f"execute if score #open {OBJ} matches 1 run function {NS}:camera/close",
        f"execute if score #open {OBJ} matches 2.. run scoreboard players remove #open {OBJ} 1",
        f"scoreboard players enable @a[scores={{{OK}=1}}] {TRIGGER}",
        f"scoreboard players remove @a[scores={{{WAIT}=1..}}] {WAIT} 1",
        f"scoreboard players set @a[scores={{{OK}=1,{HURT}=1..}}] {WAIT} {HURT_SECONDS}",
        f"scoreboard players reset @a[scores={{{HURT}=1..}}] {HURT}",
        f"execute as @a[scores={{{TRIGGER}=1..}}] run function {NS}:camera/use",
        f"execute as @a[scores={{{IN}=1}}] run function {NS}:camera/check",
    )
    # ------------------------------------------------ the creator
    menu = [gray("Camera: ")]
    hovers = {"spawn": "Spawn, from above", "board": "The standings board at spawn",
              "event": "The event on now: the arena's entrance, or a supply drop"}
    menu += [button(name, v, hovers.get(key, f"The {name} outpost")) for key, name, v in WARPS]
    menu.append(button("Leave", 1, "Back where you were, in your game mode", "yellow"))
    f[f"{FN}/use.mcfunction"] = lines(
        "# As a player who used /trigger camera: 1 toggles, 2 is the menu, 3 and up a warp.",
        f"scoreboard players operation #v {OBJ} = @s {TRIGGER}",
        f"scoreboard players set @s {TRIGGER} 0",
        f"execute if score #v {OBJ} matches 1 if score @s {IN} matches 1 run return run function {NS}:camera/leave",
        f"execute if score #v {OBJ} matches 1 run return run function {NS}:camera/enter",
        f"execute unless score @s {IN} matches 1 run " + refuse("You're not in camera. /trigger camera to go in."),
        f"execute if score #v {OBJ} matches 2 run return run function {NS}:camera/menu",
        *(f"execute if score #v {OBJ} matches {v} run return run function {NS}:camera/warp/{key}"
          for key, _, v in WARPS),
    )
    f[f"{FN}/menu.mcfunction"] = lines("tellraw @s " + text("", *menu))
    f[f"{FN}/enter.mcfunction"] = lines(
        "# As an approved creator going into camera: the rules first (docs/ADMIN.md, \"Creator camera\").",
        f"execute unless score #on {OBJ} matches 1 run " + refuse("The creator camera is off."),
        f"execute unless score @s {OK} matches 1 run " + refuse("The camera is for creators staff have approved."),
        f"execute unless score #open {OBJ} matches 1.. run " + refuse(
            "The camera only works in a camera window staff open for an event."),
        f"execute if score @s {FACTION} matches 1.. run " + refuse(
            "Faction members can't use the camera: it would show your faction where everyone is."),
        f"execute if entity @s[tag={ARENA_TAG}] run " + refuse("Not from the event arena."),
        f"execute if score @s {WAIT} matches 1.. run " + refuse(
            f"You were hurt in the last {HURT_SECONDS} seconds. Try again in a moment."),
        "execute if entity @s[gamemode=spectator] run " + refuse("You're in spectator already."),
        f"execute unless data storage {STORE} spawn.x run " + refuse("Staff haven't set the camera's spawn point."),
        "# Where to come back to, and in which game mode.",
        *(f"execute store result score @s {o} run data get entity @s Pos[{i}] 100" for i, o in enumerate(SAVED)),
        *(f"execute at @s if dimension minecraft:{d} run scoreboard players set @s {DIM} {i}"
          for i, d in enumerate(DIMENSIONS)),
        *(f"execute if entity @s[gamemode={m}] run scoreboard players set @s {MODE} {i}" for i, m in enumerate(MODES)),
        f"scoreboard players set @s {IN} 1",
        "gamemode spectator @s",
        "# Always from spawn: the leash is never around a place the creator walked to first.",
        f"function {NS}:camera/warp/spawn",
        "tellraw @a " + text("", {"selector": "@s", "color": "white"},
                             gray(" is filming with the creator camera (spectator) for this event.")),
        "tellraw @s " + text(gray(RULES)),
        f"function {NS}:camera/menu",
    )
    f[f"{FN}/anchor.mcfunction"] = lines(
        "# The leash's middle: here.",
        *(f"execute store result score @s {o} run data get entity @s Pos[{i}]"
          for i, o in zip((0, 2), ANCHOR, strict=True)),
    )
    f[f"{FN}/check.mcfunction"] = lines(
        "# Every second, as a creator in camera: out if any rule no longer holds (the leash is every tick).",
        f"execute unless score #on {OBJ} matches 1 run return run function {NS}:camera/leave",
        f"execute unless score #open {OBJ} matches 1.. run return run function {NS}:camera/leave",
        f"execute unless score @s {OK} matches 1 run return run function {NS}:camera/leave",
        f"execute if score @s {FACTION} matches 1.. run return run function {NS}:camera/leave",
        f"execute unless entity @s[gamemode=spectator] run return run function {NS}:camera/leave",
    )
    f[f"{FN}/leash.mcfunction"] = lines(
        "# Every tick, as a creator in camera: in the Overworld, within LEASH blocks of the last warp.",
        f"execute at @s unless dimension minecraft:overworld run return run function {NS}:camera/snap",
        f"execute store result score #x {OBJ} run data get entity @s Pos[0]",
        f"execute store result score #z {OBJ} run data get entity @s Pos[2]",
        f"scoreboard players operation #x {OBJ} -= @s {ANCHOR[0]}",
        f"scoreboard players operation #z {OBJ} -= @s {ANCHOR[1]}",
        f"execute unless score #x {OBJ} matches -{LEASH}..{LEASH} run return run function {NS}:camera/snap",
        f"execute unless score #z {OBJ} matches -{LEASH}..{LEASH} run return run function {NS}:camera/snap",
    )
    f[f"{FN}/snap.mcfunction"] = lines(
        "# Back to the leash's middle, in the Overworld, from above.",
        *(f"execute store result storage {STORE} at.{a} int 1 run scoreboard players get @s {o}"
          for a, o in zip("xz", ANCHOR, strict=True)),
        f"function {NS}:camera/to with storage {STORE} at",
        "title @s actionbar " + text(gray(f"The camera stays within {LEASH} blocks of its warp, in the Overworld.")),
    )
    f[f"{FN}/to.mcfunction"] = lines(
        "# Macro {x, z}: above the ground there.",
        "$execute in minecraft:overworld positioned $(x) 0 $(z) positioned over motion_blocking run tp @s ~ ~20 ~",
    )
    f[f"{FN}/leave.mcfunction"] = lines(
        "# Back where they went in, in their game mode (also when a rule takes them out).",
        *(f"execute store result storage {STORE} back.{a} double 0.01 run scoreboard players get @s {o}"
          for a, o in zip("xyz", SAVED, strict=True)),
        *(f"execute if score @s {DIM} matches {i} run data modify storage {STORE} back.dim set value \"{d}\""
          for i, d in enumerate(DIMENSIONS)),
        f"function {NS}:camera/back with storage {STORE} back",
        *(f"execute if score @s {MODE} matches {i} run gamemode {m} @s" for i, m in enumerate(MODES)),
        f"scoreboard players set @s {IN} 0",
        "tellraw @a " + text("", {"selector": "@s", "color": "white"}, gray(" stopped filming.")),
    )
    f[f"{FN}/back.mcfunction"] = lines(
        "# Macro {dim, x, y, z}.",
        "$execute in minecraft:$(dim) run tp @s $(x) $(y) $(z)",
    )
    # ------------------------------------------------ the warps
    warp = f"{FN}/warp"
    to_storage = f"function {NS}:camera/to with storage"
    f[f"{warp}/spawn.mcfunction"] = lines(
        "# The spawn point staff set with camera/set_spawn, from above.",
        f"execute unless data storage {STORE} spawn.x run " + refuse("Staff haven't set the camera's spawn point."),
        f"{to_storage} {STORE} spawn",
        f"function {NS}:camera/anchor",
    )
    f[f"{warp}/board.mcfunction"] = lines(
        "# The standings board, if its chunk is loaded; it stands at spawn, so the spawn warp otherwise.",
        f"execute unless entity @e[type=minecraft:text_display,tag={BOARD_TAG}] run return run function "
        f"{NS}:camera/warp/spawn",
        f"execute at @e[type=minecraft:text_display,tag={BOARD_TAG},limit=1] run tp @s ^ ^2 ^-6 facing ~ ~2 ~",
        f"function {NS}:camera/anchor",
    )
    for i, (key, name, _) in enumerate(DIRECTIONS, 1):
        f[f"{warp}/{key}.mcfunction"] = lines(
            f"execute unless data storage {OUTPOSTS_STORE} at.o{i}.x run " + refuse(
                f"The {name} outpost isn't placed yet."),
            f"{to_storage} {OUTPOSTS_STORE} at.o{i}",
            f"function {NS}:camera/anchor",
        )
    f[f"{warp}/event.mcfunction"] = lines(
        "# The event on now: the arena's entrance while it is open, else a supply drop's spot.",
        f"execute if score #arena ev.state matches 1 if data storage {EVENTS_STORE} arena.lx run return run "
        f"function {NS}:camera/warp/arena with storage {EVENTS_STORE} arena",
        f"execute if score #state {DROPS_OBJ} matches 1.. if data storage {DROPS_STORE} spot.x run return run "
        f"function {NS}:camera/warp/drop",
        refuse("No event on right now."),
    )
    f[f"{warp}/arena.mcfunction"] = lines(
        "$execute in minecraft:overworld run tp @s $(lx) $(ly) $(lz)",
        "execute at @s run tp @s ~ ~8 ~",
        f"function {NS}:camera/anchor",
    )
    f[f"{warp}/drop.mcfunction"] = lines(
        f"{to_storage} {DROPS_STORE} spot",
        f"function {NS}:camera/anchor",
    )
    # ------------------------------------------------ staff
    f[f"{FN}/on.mcfunction"] = lines(f"scoreboard players set #on {OBJ} 1",
                                     say({"text": "Creator camera on (it works in camera windows).", "color": "green"}))
    f[f"{FN}/off.mcfunction"] = lines(
        f"scoreboard players set #on {OBJ} 0",
        say({"text": "Creator camera off: anyone in it is put back within a second.", "color": "yellow"}))
    f[f"{FN}/open.mcfunction"] = lines(
        f"# Macro {{minutes}}: a camera window, announced (the usual one: {WINDOW_MINUTES}).",
        f"execute unless score #on {OBJ} matches 1 run " + refuse(
            f"The camera is off: /function {NS}:camera/on first."),
        f"$scoreboard players set #open {OBJ} $(minutes)",
        f"scoreboard players operation #open {OBJ} *= #60 {OBJ}",
        f"scoreboard players add #open {OBJ} 1",
        "$tellraw @a " + text("", {"text": "Creator camera: ", "color": "gold"}, gray(
            "for the next $(minutes) minutes, creators staff approved may film in spectator. Chat says who, "
            "when they start. They aren't in a faction, and they don't share where anyone is.")),
    )
    f[f"{FN}/close.mcfunction"] = lines(
        f"scoreboard players set #open {OBJ} 0",
        "tellraw @a " + text("", {"text": "Creator camera: ", "color": "gold"}, gray("the camera window is closed.")),
    )
    f[f"{FN}/set_spawn.mcfunction"] = lines(
        "# Staff, standing at spawn in the Overworld: the spawn warp (and the board's, while its chunk isn't loaded).",
        "execute unless dimension minecraft:overworld run " + refuse("Stand at spawn, in the Overworld."),
        *(f"execute store result storage {STORE} spawn.{a} int 1 run data get entity @s Pos[{i}]"
          for a, i in (("x", 0), ("z", 2))),
        say({"text": "Camera spawn point set here.", "color": "green"}),
    )
    f[f"{FN}/approve.mcfunction"] = lines(
        "# Macro {name}: approve a creator for the camera (staff only). Not a faction member.",
        f"$execute if score $(name) {FACTION} matches 1.. run " + refuse(
            "$(name) is in a faction: the camera is only for players in none."),
        f"$scoreboard players set $(name) {OK} 1",
        "$" + say({"text": "$(name) can use /trigger camera in camera windows. Tell them the rules: ",
                   "color": "green"}, gray(RULES)),
    )
    f[f"{FN}/revoke.mcfunction"] = lines(
        "# Macro {name}: no more camera (out within a second if in it now, or at their next login).",
        f"$scoreboard players reset $(name) {OK}",
        f"$scoreboard players reset $(name) {TRIGGER}",
        "$" + say({"text": "$(name) is no longer approved for the camera.", "color": "yellow"}),
    )
    f[f"{FN}/status.mcfunction"] = lines(
        say({"text": "Creator camera: on ", "color": "gold"}, {"score": {"name": "#on", "objective": OBJ}},
            gray(", window seconds left "), {"score": {"name": "#open", "objective": OBJ}},
            gray(". Approved and online: "), {"selector": f"@a[scores={{{OK}=1}}]"},
            gray(". In camera: "), {"selector": f"@a[scores={{{IN}=1}}]"}),
    )
    f[f"{FN}/help.mcfunction"] = lines(*(say({"text": c, "color": "aqua", "click_event": {
        "action": "suggest_command", "command": f"/function {NS}:camera/{c}"}}, gray(f"  {what}")) for c, what in (
        ("status", "switch, window, who"), ("on", ""), ("off", ""), ("set_spawn", "stand at spawn"),
        (f"open {{minutes:{WINDOW_MINUTES}}}", "announced camera window"), ("close", ""),
        ('approve {name:"Steve"}', "staff only grant"), ('revoke {name:"Steve"}', ""))))
    return f


def packs(repo: Repo) -> dict[Path, dict[str, str]]:
    return {repo.monkey / "datapacks" / DATAPACK: datapack_files()}
