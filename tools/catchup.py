"""The catch-up kit: a player whose first join comes after week KIT_WEEK - 1 of the season gets a modest starter kit
and a protection bubble, so joining late isn't joining naked into a world of veterans.

    python tools/datapacks.py          regenerate it with every other generated pack (--check: only compare)

Who: a first join (tools/rules.py first_join: the server has never seen them, so not anyone from test play or
pre-season, who were seen then) after the launch (#launched rw.day), once the season's week (#week rc.week, from
tools/season_calendar.py through monkey-week.timer) is KIT_WEEK or later, with the switch on. A veteran of an
earlier season counts too: the world is new to them and they are as far behind. Staff can give it to one
player by hand: `execute as NAME run function monkey:catchup/grant` (once per player per world).

The kit (KIT): iron tools, food, a bed and torches. Nothing Strength, no armor, no diamonds or netherite.

The bubble: rule 26's PvP grace (tools/rules.py: an enchanted item in the body slot that makes the player immune
to damage players cause, melee, arrows and their TNT alike) held open for BUBBLE_HOURS of the player's own play
time, counted only while they are online and outside the event arena. Each second it keeps their grace end
(monkey.grace) at least two seconds ahead and shows the time left on the action bar. It ends, whichever is
first: the hours run out; they hurt a player (rule 26's grace_attack, outside the arena); or /trigger end_grace.
Its limits, said plainly to players too (docs/SEASONS.md, "The catch-up kit"):
  - It stops damage taken, not damage dealt: the hit that ends it lands in full. A vanilla server can't cancel
    one player's outgoing damage without also crippling them against mobs (Weakness) or putting them on a team
    (one team each, which the supporter and Bounty Hunter titles already use).
  - Rule 26's 48 game hours of grace from the same first join still run alongside: the protection lasts
    whichever is longer, until the player first attacks someone.
  - Damage a player causes only indirectly (lava, a pushed fall, a mob led to them) isn't blocked, as for grace.
  - The action bar is shared: a war kill or an outpost's capture line shows over it for a moment.

The switch: `#on ck` (1 on, 0 off; CATCHUP_ON, off, is what a new world starts with). Off, nobody new gets the
kit or a bubble; bubbles already running carry on. It lives in the monkey-rules data pack, next to rule 26.
Stdlib only.
"""
from challenges import LAUNCHED
from datapacks import NS, lines, text

FN = f"data/{NS}/function/catchup"
OBJ = "ck"                 # #on: the switch; scratch
KIT_DONE = "ck.kit"        # 1 once the player has had the kit (in this world)
BUBBLE = "ck.bubble"       # seconds of play left in the bubble
HOURS, MINUTES = "ck.h", "ck.m"   # the action bar's time left
WEEK = "#week rc.week"     # the season's week, from tools/challenges.py (-1 before the timer sends one)

CATCHUP_ON = 0             # ships off (docs/SEASONS.md, "Switches")
KIT_WEEK = 4               # first joins from this week of the season on: after week 3
BUBBLE_HOURS = 8
BUBBLE_SECONDS = BUBBLE_HOURS * 3600
HOLD_TICKS = 40            # the grace end is kept this far ahead while the bubble runs
NOTE_AFTER = 3             # seconds into the bubble the chat line comes (a first join is still loading)

# (item, count): modest on purpose. A test fails if anything diamond, netherite or Strength gets in.
KIT = (
    ("minecraft:iron_pickaxe", 1),
    ("minecraft:iron_axe", 1),
    ("minecraft:iron_shovel", 1),
    ("minecraft:iron_sword", 1),
    ("minecraft:cooked_beef", 24),
    ("minecraft:red_bed", 1),
    ("minecraft:torch", 32),
)


def gray(s: str) -> dict:
    return {"text": s, "color": "gray"}


def datapack_files(grace: str, end_grace: str, arena: str) -> dict[str, str]:
    """The catch-up functions; tools/rules.py puts them in the monkey-rules pack and passes rule 26's grace
    objective, its end trigger and the arena tag."""
    f: dict[str, str] = {}
    f[f"{FN}/load.mcfunction"] = lines(
        "# Generated by tools/catchup.py, from monkey:rules/load.",
        f"scoreboard objectives add {OBJ} dummy",
        *(f"scoreboard objectives add {o} dummy" for o in (KIT_DONE, BUBBLE, HOURS, MINUTES)),
        f"execute unless score #on {OBJ} matches 0.. run scoreboard players set #on {OBJ} {CATCHUP_ON}",
        f"scoreboard players set #3600 {OBJ} 3600",
        f"scoreboard players set #60 {OBJ} 60",
    )
    f[f"{FN}/first_join.mcfunction"] = lines(
        "# From monkey:rules/first_join, as a player the server has never seen: the kit and bubble for a late",
        f"# first join (week {KIT_WEEK} or later of a launched season), while the switch is on.",
        f"execute unless score #on {OBJ} matches 1 run return 0",
        f"execute unless score {LAUNCHED} matches 1 run return 0",
        f"execute unless score {WEEK} matches {KIT_WEEK}.. run return 0",
        f"function {NS}:catchup/grant",
    )
    f[f"{FN}/grant.mcfunction"] = lines(
        "# As the player. Staff can give it by hand: execute as NAME run function monkey:catchup/grant",
        f"execute if score @s {KIT_DONE} matches 1 run return 0",
        f"scoreboard players set @s {KIT_DONE} 1",
        *(f"give @s {item} {n}" for item, n in KIT),
        f"scoreboard players set @s {BUBBLE} {BUBBLE_SECONDS}",
        f"scoreboard players enable @s {end_grace}",
    )
    f[f"{FN}/on.mcfunction"] = lines(
        "# Staff: late first joins get the kit and bubble from now on (docs/SEASONS.md, \"Switches\").",
        f"scoreboard players set #on {OBJ} 1",
        "tellraw @s " + text({"text": f"Catch-up kit on: first joins from week {KIT_WEEK} get it.",
                              "color": "green"}),
    )
    f[f"{FN}/off.mcfunction"] = lines(
        "# Staff: nobody new gets it. Bubbles already running carry on.",
        f"scoreboard players set #on {OBJ} 0",
        "tellraw @s " + text({"text": "Catch-up kit off.", "color": "yellow"}),
    )
    f[f"{FN}/second.mcfunction"] = lines(
        "# From monkey:rules/second, before rule 26's expiry check, only while someone has a bubble.",
        f"execute store result score #keep {OBJ} run time query gametime",
        f"scoreboard players add #keep {OBJ} {HOLD_TICKS}",
        f"execute as @a[scores={{{BUBBLE}=1..}}] run function {NS}:catchup/hold",
    )
    f[f"{FN}/hold.mcfunction"] = lines(
        "# As a player in the bubble: grace stays on (rule 26's item and attack check do the rest), and the hours",
        "# count down only outside the arena.",
        f"execute unless score @s {grace} >= #keep {OBJ} run scoreboard players operation @s {grace} = #keep {OBJ}",
        f"execute if entity @s[tag={arena}] run return run title @s actionbar " + text(
            gray("Protection bubble: paused in the arena")),
        f"scoreboard players remove @s {BUBBLE} 1",
        f"execute if score @s {BUBBLE} matches {BUBBLE_SECONDS - NOTE_AFTER} run function {NS}:catchup/note",
        f"execute if score @s {BUBBLE} matches 0 run return run function {NS}:catchup/over",
        f"scoreboard players operation @s {HOURS} = @s {BUBBLE}",
        f"scoreboard players operation @s {HOURS} /= #3600 {OBJ}",
        f"scoreboard players operation @s {MINUTES} = @s {BUBBLE}",
        f"scoreboard players operation @s {MINUTES} %= #3600 {OBJ}",
        f"scoreboard players operation @s {MINUTES} /= #60 {OBJ}",
        "title @s actionbar " + text(
            "", {"text": "Protection bubble: ", "color": "green"},
            {"score": {"name": "@s", "objective": HOURS}, "color": "white"}, gray("h "),
            {"score": {"name": "@s", "objective": MINUTES}, "color": "white"},
            gray("m of play left. Attacking a player ends it.")),
    )
    f[f"{FN}/note.mcfunction"] = lines(
        "tellraw @s " + text(
            {"text": "Welcome! You joined mid-season, so you get a catch-up kit ", "color": "green"},
            gray("(iron tools, food, a bed and torches) "),
            {"text": f"and a protection bubble for {BUBBLE_HOURS} hours of play: ", "color": "green"},
            gray("other players can't hurt you. It counts down only while you're online (and not in the arena), "
                 "and it ends the moment you hurt a player. "),
            {"text": f"/trigger {end_grace}", "color": "aqua",
             "click_event": {"action": "suggest_command", "command": f"/trigger {end_grace}"}},
            gray(" ends it now.")),
    )
    f[f"{FN}/over.mcfunction"] = lines(
        "# The hours ran out. Rule 26's grace lapses within two seconds, unless its own 48 hours still run.",
        f"scoreboard players reset @s {BUBBLE}",
        "title @s actionbar " + text({"text": "Your protection bubble is over.", "color": "red"}),
        "tellraw @s " + text({"text": "Your protection bubble is over.", "color": "red"}),
    )
    return f
