"""Monument of the Month: a monthly build contest between factions, voted on in Discord; winners are kept for good.

    python tools/monuments.py plan                  each month's theme and the command that opens it
    python tools/monuments.py entries WORLD         this contest's entries, ready to post in Discord for the vote
    python tools/monuments.py hall WORLD            every winner kept so far (all seasons), with its warp number
    python tools/datapacks.py                       regenerates the data pack (it ships in monkey-lore, tools/lore.py)

How a month goes (docs/SEASONS.md, "Monument of the Month"; staff commands in docs/ADMIN.md):
  1. Staff open the month's contest: `function monkey:monuments/open/<YYYY-MM>` (THEMES, the one place to edit
     them). Everyone online is told the theme.
  2. A faction builds, then a member stands at the build and runs `/trigger monument`: that records the spot (the
     block they stand on, and the dimension) for their faction (tools/diplomacy.py's number, st.faction, and its
     name). Running it again moves the entry. One entry a faction.
  3. Staff close it (`function monkey:monuments/close`): no more entries. Voting is in Discord, by hand: staff post
     each entry (`entries` above prints the posts), the faction adds a screenshot in the entry's thread, and members
     react. The bot has no part in it (the bridge only ever sends `list` and `tellraw`, and reads no world data).
  4. Staff name the winner (`function monkey:monuments/win {faction:N}`): announced in game, added to the hall
     (storage monkey:monuments hall), and the Sunday recap (tools/recap.py) names it that week.

The hall: storage monkey:monuments hall, a list of {n, season, week, month, theme, faction:{text:...}, f, x, y, z,
dim}, n numbering it from 1 for good. tools/season.py carry copies it into the next season's world, where
`function monkey:monuments/warp {n:N}` takes a player to monument N: staff give it to players through a
spawn NPC's button (docs/ADMIN.md, "Monument of the Month"). The pack never teleports a player on its own.

The switch: #on mn (MONUMENTS_ON, off). Off, /trigger monument does nothing and nobody can enter; staff can still
open, close and name winners, and the hall and warps work. Stdlib only, Python 3.10 or newer (runs on the VPS).
"""
