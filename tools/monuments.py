# ---------------------------------------------------------------- reading the saved world


def saved(world: Path) -> dict:
    """storage monkey:monuments as last saved ({} when none)."""
    return (saved_world.command_storage(world, NS) or {}).get("monuments", {})


def name_text(value) -> str:
    return value.get("text", "") if isinstance(value, dict) else str(value or "")


def hall(world: Path) -> list[dict]:
    return list(saved(world).get("hall", []))


def entries_text(world: Path) -> str:
    """One Discord post per entry, for the vote (docs/ADMIN.md, "Monument of the Month")."""
    data = saved(world)
    contest = data.get("contest", {})
    if not contest:
        return "No contest has been opened in this world."
    head = f"Monument of the Month, {contest.get('month', '?')}: {contest.get('theme', '?')}."
    entries = data.get("entries", {})
    if not entries:
        return head + "\nNo entries."
    out = [head]
    for key in sorted(entries, key=lambda k: int(k[1:]) if k[1:].isdigit() else 0):
        e = entries[key]
        out.append(f"**{name_text(e.get('faction'))}** (faction {e.get('f')}): {e.get('x')} {e.get('y')} {e.get('z')}"
                   f" in {str(e.get('dim', '')).removeprefix('minecraft:')}. Screenshot: posted by the faction in "
                   "this thread. React to vote. (Win: function monkey:monuments/win {faction:" + str(e.get('f')) + "})")
    return "\n".join(out)


def hall_text(world: Path) -> str:
    rows = hall(world)
    if not rows:
        return "No monuments yet."
    return "\n".join(f"{r.get('n')}. Season {r.get('season')}, {r.get('month')}, {r.get('theme')}: "
                     f"{name_text(r.get('faction'))} at {r.get('x')} {r.get('y')} {r.get('z')} "
                     f"({str(r.get('dim', '')).removeprefix('minecraft:')})" for r in rows)


def carry_lines(world: Path) -> list[str]:
    """For tools/season.py carry: the commands that put the hall back in the next season's world."""
    rows = hall(world)
    if not rows:
        return []
    return [f"data modify storage {STORE} hall set value {snbt(rows)}"]


def plan() -> str:
    return "\n".join(f"{month:<14} {theme}: {about}  (function {NS}:monuments/open/{key})"
                     for key, (month, theme, about) in THEMES.items())


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="Monument of the Month: themes, entries and the hall.")
    sub = ap.add_subparsers(dest="command", required=True)
    sub.add_parser("plan", help="each month's theme and the command that opens it")
    for name, about in (("entries", "this contest's entries, as Discord posts"), ("hall", "every winner kept")):
        p = sub.add_parser(name, help=about)
        p.add_argument("world", type=Path, help="the world folder (run save-all first for the latest)")
    args = ap.parse_args(argv)
    if args.command == "plan":
        print(plan())
    elif args.command == "entries":
        print(entries_text(args.world))
    else:
        print(hall_text(args.world))
    return 0


if __name__ == "__main__":
    sys.exit(main())

