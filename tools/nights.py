"""Generate the monkey-nights data pack: Saturday event nights that run on their own.

    python tools/datapacks.py   writes it (with every other pack); --check is part of tools/checks.py

Launch night (Sat 7 Nov 2026), from Diego's schedule:
  5:00 PM  grace/start   90 min grace: PvP off, Nether portals closed, boss bar countdown
  6:30 PM  grace/end     PvP and the Nether open, then build/start runs by itself
  6:30 PM  build/start   Rise of Kingdoms build battle, 180 min boss bar countdown
  9:30 PM  build/end     "Building is over", staff judge

The in-game countdown ends each phase by itself. The VPS sends the same functions at the wall-clock
times (one-shot systemd timers, see docs/ADMIN.md "Event nights"), so a lagging or empty server still
switches on time; each end function does nothing unless its phase is running, so the two never double up.
Staff can run every step by hand.

Only vanilla commands. It shares nothing with monkey-rules or monkey-events, so those can stay off.
"""

from __future__ import annotations

import json
from pathlib import Path

from datapacks import DATA_FORMAT, NS
from repo import Repo

DATAPACK = "monkey-nights"
FN = f"data/{NS}/function/nights"
F = f"{NS}:nights"
OBJ_STATE = "nt.state"
OBJ_TIMER = "nt.timer"
BAR = f"{NS}:nights"
GRACE_MINUTES = 90
BUILD_MINUTES = 180


def js(obj) -> str:
    return json.dumps(obj, ensure_ascii=False, separators=(",", ":"))


def lines(*rows: str) -> str:
    return "\n".join(rows) + "\n"


def tell(target: str, *parts) -> str:
    return f"tellraw {target} {js(list(parts))}"


TAG = {"text": "[Monkey SMP] ", "color": "gold"}
BUSY = {"text": "An event night phase is already running. /function monkey:nights/stop cancels it.", "color": "red"}
IDLE = {"text": "Nothing is running.", "color": "red"}
SCORE_MIN = {"score": {"name": "#min", "objective": OBJ_TIMER}, "color": "white"}


def pack_files() -> dict[str, str]:
    f: dict[str, str] = {}
    f["pack.mcmeta"] = json.dumps(
        {"pack": {"description": "Monkey SMP event nights: launch grace + build battle on a timer "
                                 "(generated by tools/nights.py)",
                  "min_format": DATA_FORMAT, "max_format": DATA_FORMAT}}, indent=2) + "\n"
    f["data/minecraft/tags/function/load.json"] = json.dumps({"values": [f"{F}/load"]}, indent=2) + "\n"

    f[f"{FN}/load.mcfunction"] = lines(
        "# Generated by tools/nights.py. Scores, the boss bar and the phase survive restarts.",
        f"scoreboard objectives add {OBJ_STATE} dummy",
        f"scoreboard objectives add {OBJ_TIMER} dummy",
        f"scoreboard players set #60 {OBJ_TIMER} 60",
        f"execute unless score #phase {OBJ_STATE} matches 0.. run scoreboard players set #phase {OBJ_STATE} 0",
        f"schedule function {F}/second 20t replace",
    )
    # #phase: 0 idle, 1 grace, 2 build battle. #left: seconds left in the phase.
    f[f"{FN}/second.mcfunction"] = lines(
        f"schedule function {F}/second 20t replace",
        f"execute if score #phase {OBJ_STATE} matches 1.. run function {F}/tick",
    )
    f[f"{FN}/tick.mcfunction"] = lines(
        f"scoreboard players remove #left {OBJ_TIMER} 1",
        f"execute store result bossbar {BAR} value run scoreboard players get #left {OBJ_TIMER}",
        f"scoreboard players operation #sec {OBJ_TIMER} = #left {OBJ_TIMER}",
        f"scoreboard players operation #sec {OBJ_TIMER} %= #60 {OBJ_TIMER}",
        f"execute if score #sec {OBJ_TIMER} matches 0 run function {F}/bar",
        # Grace warnings
        f"execute if score #phase {OBJ_STATE} matches 1 if score #left {OBJ_TIMER} matches 600 run "
        + tell("@a", TAG, {"text": "PvP and the Nether open in 10 minutes.", "color": "red"}),
        f"execute if score #phase {OBJ_STATE} matches 1 if score #left {OBJ_TIMER} matches 300 run "
        + tell("@a", TAG, {"text": "PvP and the Nether open in 5 minutes. Get home!", "color": "red"}),
        f"execute if score #phase {OBJ_STATE} matches 1 if score #left {OBJ_TIMER} matches 60 run "
        + tell("@a", TAG, {"text": "PvP and the Nether open in 1 minute.", "color": "red"}),
        # Build warnings
        f"execute if score #phase {OBJ_STATE} matches 2 if score #left {OBJ_TIMER} matches 1800 run "
        + tell("@a", TAG, {"text": "Rise of Kingdoms: 30 minutes of building left.", "color": "yellow"}),
        f"execute if score #phase {OBJ_STATE} matches 2 if score #left {OBJ_TIMER} matches 600 run "
        + tell("@a", TAG, {"text": "Rise of Kingdoms: 10 minutes left. Finish your base!", "color": "yellow"}),
        f"execute if score #phase {OBJ_STATE} matches 2 if score #left {OBJ_TIMER} matches 60 run "
        + tell("@a", TAG, {"text": "Rise of Kingdoms: 1 minute left.", "color": "yellow"}),
        f"execute if score #left {OBJ_TIMER} matches ..0 if score #phase {OBJ_STATE} matches 1 run "
        f"return run function {F}/grace/end",
        f"execute if score #left {OBJ_TIMER} matches ..0 if score #phase {OBJ_STATE} matches 2 run "
        f"return run function {F}/build/end",
    )
    # Refreshes the bar's name (minutes left, rounded up) and shows it to everyone online, so late joiners
    # see it within a minute.
    f[f"{FN}/bar.mcfunction"] = lines(
        f"scoreboard players operation #min {OBJ_TIMER} = #left {OBJ_TIMER}",
        f"scoreboard players add #min {OBJ_TIMER} 59",
        f"scoreboard players operation #min {OBJ_TIMER} /= #60 {OBJ_TIMER}",
        f"execute if score #phase {OBJ_STATE} matches 1 run bossbar set {BAR} name "
        + js([{"text": "Grace period: ", "color": "green"}, SCORE_MIN,
              {"text": " min left  |  no PvP, Nether closed", "color": "green"}]),
        f"execute if score #phase {OBJ_STATE} matches 2 run bossbar set {BAR} name "
        + js([{"text": "Rise of Kingdoms: ", "color": "gold"}, SCORE_MIN,
              {"text": " min of building left", "color": "gold"}]),
        f"bossbar set {BAR} players @a",
    )

    def new_bar(seconds: int, color: str) -> list[str]:
        return [
            f"bossbar remove {BAR}",
            f"bossbar add {BAR} {js({'text': 'Monkey SMP'})}",
            f"bossbar set {BAR} color {color}",
            f"bossbar set {BAR} max {seconds}",
            f"bossbar set {BAR} value {seconds}",
            f"bossbar set {BAR} visible true",
            f"scoreboard players set #left {OBJ_TIMER} {seconds}",
            f"function {F}/bar",
        ]

    grace_s = GRACE_MINUTES * 60
    build_s = BUILD_MINUTES * 60

    f[f"{FN}/grace/start.mcfunction"] = lines(
        "# 5:00 PM (sent by the VPS, or an admin runs it): the 90-minute grace period.",
        f"execute if score #phase {OBJ_STATE} matches 1.. run return run "
        + tell("@s", BUSY),
        "gamerule pvp false",
        "gamerule allow_entering_nether_using_portals false",
        f"scoreboard players set #phase {OBJ_STATE} 1",
        *new_bar(grace_s, "green"),
        "title @a times 10 80 20",
        "title @a subtitle " + js({"text": "Grace: no PvP, Nether closed for 90 minutes", "color": "yellow"}),
        "title @a title " + js({"text": "The Path To Strength", "color": "gold"}),
        "execute as @a at @s run playsound minecraft:event.raid.horn master @s ~ ~ ~ 1 1",
        tell("@a", TAG, {"text": "Season I has begun! For 90 minutes there is no PvP and the Nether is closed. "
                                 "Make your faction with ", "color": "yellow"},
             {"text": "/oparties create", "color": "aqua"},
             {"text": ", name it with ", "color": "yellow"},
             {"text": "/opac player-config set parties.name <name>", "color": "aqua"},
             {"text": ", and claim your land with ", "color": "yellow"},
             {"text": "/oclaims", "color": "aqua"},
             {"text": ". At 6:30 the Rise of Kingdoms build battle starts.", "color": "yellow"}),
    )
    f[f"{FN}/grace/end.mcfunction"] = lines(
        "# 6:30 PM (the countdown, the VPS, or an admin): PvP and the Nether open, then the build battle.",
        f"execute unless score #phase {OBJ_STATE} matches 1 run return run "
        + tell("@s", {"text": "No grace period is running.", "color": "red"}),
        "gamerule pvp true",
        "gamerule allow_entering_nether_using_portals true",
        f"scoreboard players set #phase {OBJ_STATE} 0",
        tell("@a", TAG, {"text": "The grace period is over: PvP and the Nether are open.", "color": "red"}),
        f"function {F}/build/start",
    )
    f[f"{FN}/build/start.mcfunction"] = lines(
        "# Rise of Kingdoms: 3 hours, judged by staff per faction at the end.",
        f"execute if score #phase {OBJ_STATE} matches 1.. run return run "
        + tell("@s", BUSY),
        f"scoreboard players set #phase {OBJ_STATE} 2",
        *new_bar(build_s, "yellow"),
        "title @a times 10 80 20",
        "title @a subtitle " + js({"text": "PvP and the Nether are open. Build until 9:30!", "color": "red"}),
        "title @a title " + js({"text": "Rise of Kingdoms", "color": "gold"}),
        "execute as @a at @s run playsound minecraft:event.raid.horn master @s ~ ~ ~ 1 1",
        tell("@a", TAG, {"text": "Rise of Kingdoms has started! Staff judge each faction's base at the end:",
                         "color": "yellow"}),
        tell("@a", {"text": " custom faction banner (1-3), a full 3-high custom wall around your land (1-3), "
                            "animal farm (1-2), trading post (1-2), house (1-5), automated build (1-3), "
                            "rare items (1-4), "
                            "and 2 points for each block we call out tonight.", "color": "gray"}),
        tell("@a", {"text": " Prizes: a mace, a smithing template and 64 golden apples, plus +1 Strength.",
                    "color": "gray"}),
    )
    f[f"{FN}/build/end.mcfunction"] = lines(
        "# 9:30 PM (the countdown, the VPS, or an admin): building stops, staff judge.",
        f"execute unless score #phase {OBJ_STATE} matches 2 run return run "
        + tell("@s", {"text": "No build battle is running.", "color": "red"}),
        f"scoreboard players set #phase {OBJ_STATE} 0",
        f"bossbar remove {BAR}",
        "title @a times 10 80 20",
        "title @a subtitle " + js({"text": "Staff are judging the bases now", "color": "yellow"}),
        "title @a title " + js({"text": "Building is over", "color": "gold"}),
        "execute as @a at @s run playsound minecraft:ui.toast.challenge_complete master @s ~ ~ ~ 1 1",
        tell("@a", TAG, {"text": "Rise of Kingdoms is over. Thanks for building! Staff will judge and hand out "
                                 "the rewards.", "color": "gold"}),
    )
    f[f"{FN}/stop.mcfunction"] = lines(
        "# Cancels whatever phase runs. Game rules stay as they are: check them after.",
        f"execute unless score #phase {OBJ_STATE} matches 1.. run return run "
        + tell("@s", IDLE),
        f"scoreboard players set #phase {OBJ_STATE} 0",
        f"bossbar remove {BAR}",
        tell("@a", TAG, {"text": "Staff stopped the event timer.", "color": "gray"}),
        tell("@s", {"text": "Stopped. Game rules unchanged: check /gamerule pvp and "
                            "/gamerule allow_entering_nether_using_portals.", "color": "yellow"}),
    )
    # {minutes:N}: sets the minutes left in the running phase (1 to 600). A non-number fails the macro whole.
    f[f"{FN}/minutes.mcfunction"] = lines(
        f"execute unless score #phase {OBJ_STATE} matches 1.. run return run "
        + tell("@s", IDLE),
        f"$scoreboard players set #new {OBJ_TIMER} $(minutes)",
        f"execute unless score #new {OBJ_TIMER} matches 1..600 run return run "
        + tell("@s", {"text": "minutes must be 1 to 600.", "color": "red"}),
        f"scoreboard players operation #left {OBJ_TIMER} = #new {OBJ_TIMER}",
        f"scoreboard players operation #left {OBJ_TIMER} *= #60 {OBJ_TIMER}",
        f"execute store result bossbar {BAR} max run scoreboard players get #left {OBJ_TIMER}",
        f"execute store result bossbar {BAR} value run scoreboard players get #left {OBJ_TIMER}",
        f"function {F}/bar",
        tell("@s", {"text": "Time left set to ", "color": "green"},
             {"score": {"name": "#new", "objective": OBJ_TIMER}, "color": "white"},
             {"text": " minutes.", "color": "green"}),
    )
    # {block:"Copper Bulb"}: announces a called-out block. The name goes through storage, so it never
    # becomes command text; a name with a " in it fails the macro whole.
    f[f"{FN}/call.mcfunction"] = lines(
        f'$data modify storage {NS}:nights call set value "$(block)"',
        "title @a times 10 60 20",
        "title @a subtitle " + js({"storage": f"{NS}:nights", "nbt": "call", "color": "aqua"}),
        "title @a title " + js({"text": "Called-out block", "color": "gold"}),
        tell("@a", TAG, {"text": "Called-out block: ", "color": "yellow"},
             {"storage": f"{NS}:nights", "nbt": "call", "color": "aqua"},
             {"text": " (2 points for each faction that uses it in its base)", "color": "gray"}),
    )

    def cmd(c: str, note: str) -> str:
        click = {"action": "suggest_command", "command": "/function " + c}
        return tell("@s", {"text": " " + c, "color": "aqua", "click_event": click},
                    {"text": "  " + note, "color": "dark_gray"})

    f[f"{FN}/help.mcfunction"] = lines(
        tell("@s", {"text": "Event night commands (the VPS runs the timed ones by itself):", "color": "gold"}),
        cmd(f"{F}/grace/start", "5:00 PM, 90 min no PvP, Nether closed"),
        cmd(f"{F}/grace/end", "6:30 PM, opens PvP + Nether, starts the build battle"),
        cmd(f"{F}/build/start", "start the build battle (3 hours)"),
        cmd(f"{F}/build/end", "9:30 PM, building over"),
        cmd(f"{F}/minutes {{minutes:30}}", "change the minutes left"),
        cmd(f'{F}/call {{block:"Copper Bulb"}}', "announce a called-out block"),
        cmd(f"{F}/stop", "cancel the timer (game rules stay)"),
    )
    return f


def packs(repo: Repo) -> dict[Path, dict[str, str]]:
    return {repo.monkey / "datapacks" / DATAPACK: pack_files()}
